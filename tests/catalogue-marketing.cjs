const evil=products({newArrivals:[malicious]})[0];
html=render({newArrivals:[malicious]},evil.route,templates,{now}).body;
assert.doesNotMatch(html,/<script>alert\(1\)/);
assert.equal(schema(html).name,malicious.name);
